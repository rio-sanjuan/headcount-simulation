"""Tests for the dependency license check. No network access."""

from __future__ import annotations

import pytest

from tools.licenses import Metadata, Verdict, classify, parse_pins


def meta(expression: str = "", license: str = "", *classifiers: str) -> Metadata:
    return Metadata("pkg", "1.0", expression, license, classifiers)


@pytest.mark.parametrize(
    ("package", "verdict"),
    [
        (meta("MIT"), Verdict.OK),
        (meta("Apache-2.0 OR GPL-2.0-only"), Verdict.OK),
        (meta("GPL-3.0-or-later"), Verdict.INCOMPATIBLE),
        (meta("AGPL-3.0-only"), Verdict.INCOMPATIBLE),
        (meta("LGPL-2.1-or-later"), Verdict.OK),
        (meta("MPL-2.0"), Verdict.OK),
        (meta("", "", "License :: OSI Approved :: BSD License"), Verdict.OK),
        (
            meta("", "", "License :: OSI Approved :: GNU General Public License v3 (GPLv3)"),
            Verdict.INCOMPATIBLE,
        ),
        (
            meta(
                "", "", "License :: OSI Approved :: GNU Lesser General Public License v3 (LGPLv3)"
            ),
            Verdict.OK,
        ),
        (
            meta(
                "",
                "",
                "License :: OSI Approved :: MIT License",
                "License :: OSI Approved :: GNU General Public License (GPL)",
            ),
            Verdict.REVIEW,
        ),
        (meta("", "SSPL-1.0"), Verdict.INCOMPATIBLE),
        (meta("", "Business Source License 1.1"), Verdict.INCOMPATIBLE),
        (meta("", ""), Verdict.UNKNOWN),
        (meta("", "UNKNOWN"), Verdict.UNKNOWN),
    ],
)
def test_classification(package: Metadata, verdict: Verdict) -> None:
    assert classify(package) is verdict


def test_a_long_license_field_is_treated_as_license_text_not_a_signal() -> None:
    full_text = "Permission is hereby granted... unlike the GNU General Public License... " * 5
    assert classify(meta("", full_text, "License :: OSI Approved :: MIT License")) is Verdict.OK


def test_pins_are_parsed_from_uv_export_output() -> None:
    exported = (
        "# generated by uv\n"
        "numpy==2.3.5 \\\n    --hash=sha256:abc\n"
        "torch==2.14.1 ; sys_platform == 'linux' \\\n    --hash=sha256:def\n"
        "-e .\n"
    )
    assert parse_pins(exported) == [("numpy", "2.3.5"), ("torch", "2.14.1")]
